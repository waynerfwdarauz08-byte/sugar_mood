const {test} = require('node:test');
const assert = require('node:assert/strict');
const request = require('supertest');
test('Stock concurrente, entregas, filtros, ventas y revocación de sesiones', {skip:process.env.RUN_MYSQL_TESTS !== '1'}, async () => {
  assert.match(process.env.DB_TEST_NAME,/^sugar_mood_test_\d+_[a-f0-9]+$/);
  const db=require('../models'), app=require('../app'), auth=require('../services/authService'), api=request(app);
  try {
    const role=await db.Rol.findOne({where:{codigo:'administrador'}});
    const user=await db.Usuario.create({nombre:'Mejoras',correo:'mejoras@prueba.local',password:await auth.hash('Mejoras2026!'),id_rol:role.id});
    const login=async (correo=user.correo,password='Mejoras2026!')=>api.post('/api/auth/login').send({correo,password});
    const token=(await login()).body.token;
    const call=async(method,path,body,status=200,bearer=token)=>{const r=await api[method]('/api/'+path).set('Authorization','Bearer '+bearer).send(body);assert.equal(r.status,status,JSON.stringify(r.body));return r.body;};
    const c=await call('post','categorias',{nombre:'Inventario pruebas'},201);
    const product=await call('post','productos',{categoriaId:c.id,nombre:'Última paleta',precio:'0.10',stock:1,stockMinimo:2},201);
    assert.equal(product.stockBajo,true);
    const client1=await call('post','clientes',{nombre:'Entrega A',telefono:'0000-1010'},201);
    const client2=await call('post','clientes',{nombre:'Entrega B',telefono:'0000-2020'},201);
    const body={clienteId:client1.id,fecha:'2027-01-15T10:00:00-06:00',fechaEntrega:'2027-01-15T18:00:00-06:00',observaciones:'Sin azúcar extra',detalles:[{productoId:product.id,cantidad:1}]};
    await call('post','pedidos',{...body,fechaEntrega:'2027-01-14T12:00:00-06:00'},400);
    await call('post','pedidos',{...body,observaciones:'a'.repeat(501)},400);
    await call('post','productos',{categoriaId:c.id,nombre:'Inválido',precio:'1',stock:-1},400);
    const race=await Promise.all([client1,client2].map(client=>api.post('/api/pedidos').set('Authorization','Bearer '+token).send({...body,clienteId:client.id})));
    assert.deepEqual(race.map(r=>r.status).sort(),[201,409]);
    let order=race.find(r=>r.status===201).body;
    const own={...body,clienteId:order.clienteId};
    const stock=async()=> (await call('get','productos/'+product.id)).stock;
    assert.equal(await stock(),0);
    await call('put','pedidos/'+order.id,{...own,detalles:[{productoId:product.id,cantidad:2}]},409);
    assert.equal(await stock(),0);
    assert.equal((await call('get','pedidos/'+order.id)).detalles[0].cantidad,1);
    order=await call('put','pedidos/'+order.id,{...own,estado:'cancelado'});
    assert.equal(await stock(),1);
    await call('put','pedidos/'+order.id,{...own,estado:'cancelado'});
    assert.equal(await stock(),1,'Cancelar dos veces no duplica stock');
    order=await call('put','pedidos/'+order.id,{...own,estado:'preparado'});
    assert.equal(await stock(),0);
    await call('put','detalles-pedido/'+order.detalles[0].id,{cantidad:2},409);
    await call('put','productos/'+product.id,{categoriaId:c.id,nombre:product.nombre,precio:'9.99',stock:10});
    order=await call('put','pedidos/'+order.id,{...own,estado:'preparado',detalles:[{productoId:product.id,cantidad:3}]});
    assert.equal(await stock(),8);assert.equal(order.total,'0.30','Se conserva precio histórico');
    const extra=await call('post','productos',{categoriaId:c.id,nombre:'Extra inventario',precio:'0.20',stock:5},201);
    const detail=await call('post','detalles-pedido',{pedidoId:order.id,productoId:extra.id,cantidad:2},201);
    assert.equal((await call('get','productos/'+extra.id)).stock,3);
    await call('put','detalles-pedido/'+detail.id,{cantidad:3});
    assert.equal((await call('get','productos/'+extra.id)).stock,2);
    await call('delete','detalles-pedido/'+detail.id,undefined,204);
    assert.equal((await call('get','productos/'+extra.id)).stock,5);
    const delivery=order.fechaEntrega;
    order=await call('put','pedidos/'+order.id,{clienteId:order.clienteId,fecha:body.fecha,estado:'entregado',detalles:[{productoId:product.id,cantidad:3}]});
    assert.equal(order.fechaEntrega,delivery);assert.equal(order.observaciones,body.observaciones);
    await call('put','pedidos/'+order.id,own,409);
    await call('delete','pedidos/'+order.id,undefined,409);
    await call('put','detalles-pedido/'+order.detalles[0].id,{cantidad:1},409);
    await call('delete','detalles-pedido/'+order.detalles[0].id,undefined,409);
    assert.equal(await stock(),8);
    const previous=await call('post','pedidos',{...own,fecha:'2027-01-14T23:59:59-06:00',estado:'entregado',detalles:[{productoId:extra.id,cantidad:1}]},201);
    await call('post','pedidos',{...own,estado:'pendiente'},201);
    const createDetail=db.DetallePedido.create;
    const beforeOrders=await db.Pedido.count();
    db.DetallePedido.create=async function(values,options) {
      if(values.productoId===extra.id) throw new Error('Fallo deliberado después de reservar inventario');
      return createDetail.call(this,values,options);
    };
    try {
      await call('post','pedidos',{...own,detalles:[{productoId:product.id,cantidad:1},{productoId:extra.id,cantidad:1}]},500);
    } finally {db.DetallePedido.create=createDetail;}
    assert.equal(await stock(),7,'Un fallo después de reservar revierte las existencias');
    assert.equal((await call('get','productos/'+extra.id)).stock,4);
    assert.equal(await db.Pedido.count(),beforeOrders,'El pedido parcial tampoco persiste');
    const filtered=await call('get',`pedidos?desde=2027-01-15&hasta=2027-01-15&estado=entregado&clienteId=${order.clienteId}&buscar=${order.id}`);
    assert.deepEqual(filtered.map(o=>o.id),[order.id]);
    assert.equal((await call('get','pedidos?buscar=Entrega')).length>=2,true);
    assert.equal((await call('get','pedidos?buscar=%25')).length,0);
    await call('get','pedidos?desde=2027-02-30',undefined,400);
    await call('get','pedidos?desde=2027-02-01&hasta=2027-01-01',undefined,400);
    const sales=await call('get','reportes/ventas?desde=2027-01-15&hasta=2027-01-15');
    assert.equal(sales.resumen.total,'0.30');assert.equal(sales.resumen.pedidos,1);assert.equal(sales.resumen.unidades,3);assert.equal(sales.resumen.ticketPromedio,'0.30');
    assert.equal(sales.anterior.total,'0.20');assert.equal(sales.variacionPorcentaje,50);assert.equal(sales.productos[0].productoId,product.id);assert.equal(sales.dias[0].total,'0.30');
    assert.equal(previous.estado,'entregado');
    await call('get','reportes/ventas?desde=2020-01-01&hasta=2027-01-01',undefined,400);
    const empty=await call('get','reportes/ventas?desde=2030-01-01&hasta=2030-01-02');
    assert.equal(empty.resumen.total,'0.00');assert.equal(empty.variacionPorcentaje,null);assert.equal(empty.dias.length,2);
    // Pedidos anteriores a la migración no inventan existencias al cancelarse.
    const legacy=await db.Pedido.create({clienteId:client1.id,fecha:new Date(),stockAplicado:false});
    await db.DetallePedido.create({pedidoId:legacy.id,productoId:product.id,cantidad:100,precioUnitario:'0.10'});
    await call('put','pedidos/'+legacy.id,{...own,estado:'cancelado',detalles:[{productoId:product.id,cantidad:100}]});
    assert.equal(await stock(),7);
    await call('delete','pedidos/'+legacy.id,undefined,204);assert.equal(await stock(),7);
    // Cambio de clave invalida tanto el token propio como los de otras sesiones.
    const registered=await api.post('/api/auth/register').send({nombre:'Cliente nuevo',correo:'nueva@prueba.local',password:'Anterior2026!',telefono:'0000-3030'});
    assert.equal(registered.status,201);
    const first=(await login('nueva@prueba.local','Anterior2026!')).body.token;
    const second=(await login('nueva@prueba.local','Anterior2026!')).body.token;
    await call('get','reportes/ventas',undefined,403,first);
    await call('get',`pedidos?clienteId=${client1.id}`,undefined,403,first);
    await call('get','pedidos/'+order.id,undefined,404,first);
    await call('post','auth/change-password',{passwordActual:'incorrecta',passwordNueva:'NuevaClave2026!'},400,first);
    await call('post','auth/change-password',{passwordActual:'Anterior2026!',passwordNueva:'NuevaClave2026!',id:1},400,first);
    await call('post','auth/change-password',{passwordActual:'Anterior2026!',passwordNueva:'NuevaClave2026!'},204,first);
    await call('get','auth/me',undefined,401,second);
    assert.equal((await login('nueva@prueba.local','Anterior2026!')).status,401);
    const active=(await login('nueva@prueba.local','NuevaClave2026!')).body;
    const account=await call('get','usuarios/'+active.usuario.id);
    const changes={nombre:account.nombre,correo:account.correo,id_rol:account.id_rol,activo:false};
    await call('put','usuarios/'+account.id,changes);
    await call('get','auth/me',undefined,401,active.token);
    assert.equal((await login(account.correo,'NuevaClave2026!')).status,401);
    await call('put','usuarios/'+account.id,{...changes,activo:true});
    await call('get','auth/me',undefined,401,active.token);
    assert.equal((await login(account.correo,'NuevaClave2026!')).status,200);
    const browser=request.agent(app);
    const csrf=(await browser.get('/api/auth/csrf').set('X-Session-Mode','cookie')).body.csrfToken;
    const browserLogin=await browser.post('/api/auth/login').set('X-Session-Mode','cookie').set('X-CSRF-Token',csrf).send({correo:account.correo,password:'NuevaClave2026!'});
    assert.equal(browserLogin.status,200);
    const changed=await browser.post('/api/auth/change-password').set('X-Session-Mode','cookie').set('X-CSRF-Token',browserLogin.body.csrfToken).send({passwordActual:'NuevaClave2026!',passwordNueva:'TerceraClave2026!'});
    assert.equal(changed.status,204);
    assert.ok(changed.headers['set-cookie'].some(c=>c.startsWith('sugar_mood_session=;')));
    assert.equal((await browser.get('/api/auth/me')).status,401);
    const others=await db.Usuario.findAll({where:{id_rol:role.id,activo:true}});
    for(const other of others.filter(u=>u.id!==user.id)) await call('put','usuarios/'+other.id,{nombre:other.nombre,correo:other.correo,id_rol:role.id,activo:false});
    await call('put','usuarios/'+user.id,{nombre:user.nombre,correo:user.correo,id_rol:role.id,activo:false},409);
    await call('get','auth/me');
  } finally {await db.sequelize.close();}
});
